def exit_probe(r, ns, config, path, dnsmasq):
    upstream = next(line for line in config.splitlines() if line.startswith('server=fd'))
    exit_ip, router_ip = upstream.removeprefix('server=').split('#53@')
    ns('bootstrap', 'ip', '-6', 'addr', 'add', router_ip + '/128', 'dev', 'v3', 'nodad')
    ns('dns-wan', 'ip', '-6', 'addr', 'add', exit_ip + '/128', 'dev', 'remote', 'nodad')
    ns('bootstrap', 'ip', '-6', 'route', 'add', exit_ip + '/128', 'dev', 'v3')
    ns('dns-wan', 'ip', '-6', 'route', 'add', router_ip + '/128', 'dev', 'remote')
    loopback = next(line for line in config.splitlines() if line.startswith('server=/fips/'))
    loop_ip, loop_port = loopback.removeprefix('server=/fips/').split('#')
    fips_name = 'split-' + os.urandom(8).hex() + '.fips'
    exit_count, loop_count = r.tmp / 'exit-count', r.tmp / 'loop-count'
    public_name = 'public-' + os.urandom(16).hex() + '.example.com'
    fixture = r.popen_ns('dns-wan', ['python3', '-u', '-c', DNS_FIXTURE, exit_ip, '53', router_ip, public_name, '192.0.2.73', str(exit_count)])
    local = r.popen_ns('bootstrap', ['python3', '-u', '-c', DNS_FIXTURE, loop_ip, loop_port, loop_ip, fips_name, '192.0.2.74', str(loop_count)])
    wan_count = r.tmp / 'wan-count'
    wan = r.popen_ns('dns-wan', ['python3', '-u', '-c', DNS_FIXTURE, '10.73.3.2', '53', '10.73.3.1', 'wan-control.example', '192.0.2.75', str(wan_count)])
    daemon = r.popen_ns('bootstrap', [dnsmasq, '--keep-in-foreground', '--conf-file=' + str(path), '--user=nobody', '--group=nogroup', '--pid-file='])
    for attempt in range(30):
        assert fixture.poll() is None and local.poll() is None and wan.poll() is None and daemon.poll() is None, 'DNS process exited before readiness'
        if exit_count.exists() and loop_count.exists() and wan_count.exists() and '10.73.1.1:5353' in ns('bootstrap', 'ss', '-lun').stdout:
            break
        time.sleep(0.1)
    else:
        raise RuntimeError('DNS listeners not ready within 3 seconds')
    wan_before = int(wan_count.read_text())
    response = json.loads(ns('bootstrap', 'python3', '-c', PROBE, 'wan-control.example', '2', '10.73.3.2', '53').stdout)
    assert response['rcode'] == 0 and response['answers'] == 1 and response['last_ipv4'] == '192.0.2.75', response
    wan_control_count = int(wan_count.read_text())
    assert wan.poll() is None and wan_before == 0 and wan_control_count == wan_before + 1, 'WAN positive control not counted'
    print(json.dumps(dict(case='WAN IPv4 UDP positive control', wan_queries_before=wan_before, wan_queries_after=wan_control_count, **response)), flush=True)
    print('FIXTURE: IPv6 veth; labelled UDP DNS exit; no real FIPS transport', flush=True)
    response = json.loads(ns('dns-guest', 'python3', '-c', PROBE, public_name).stdout)
    print(json.dumps(response), flush=True)
    assert response['rcode'] == 0 and response['answers'] == 1 and response['last_ipv4'] == '192.0.2.73', response
    assert wan.poll() is None and int(wan_count.read_text()) == wan_control_count
    print(json.dumps(dict(case='exit-up IPv4 UDP WAN fallback', wan_before=wan_control_count, wan_after=int(wan_count.read_text()))), flush=True)
    before = int(exit_count.read_text())
    assert before == 1, before
    response = json.loads(ns('dns-guest', 'python3', '-c', PROBE, fips_name).stdout)
    print(json.dumps(response), flush=True)
    assert response['rcode'] == 0 and response['answers'] == 1 and response['last_ipv4'] == '192.0.2.74', response
    time.sleep(0.2)  # bounded observation after the loopback response
    after = int(exit_count.read_text())
    assert fixture.poll() is None and local.poll() is None, 'fixture assertion failed'
    assert int(loop_count.read_text()) == 1 and after == before, 'split query reached exit or missed loopback'
    print(json.dumps(dict(loopback_listener=loop_ip + ':' + loop_port, loopback_queries=1, exit_queries_before=before, exit_queries_after=after)), flush=True)
    portal_before = [int(p.read_text()) for p in (exit_count, loop_count)]
    response = json.loads(ns('dns-guest', 'python3', '-c', PROBE, 'portal.example').stdout)
    print(json.dumps(response), flush=True)
    assert response['rcode'] == 0 and response['answers'] == 1 and response['last_ipv4'] == '10.73.1.1', response
    time.sleep(0.2)  # bounded observation after the local portal response
    portal_after = [int(p.read_text()) for p in (exit_count, loop_count)]
    assert fixture.poll() is None and local.poll() is None, 'fixture assertion failed'
    assert portal_after == portal_before, 'portal query reached exit or loopback fixture'
    print(json.dumps(dict(portal_fixture_order=['exit', 'fips'], portal_counts_before=portal_before, portal_counts_after=portal_after)), flush=True)
    print(json.dumps(dict(expected_router_source=router_ip, exit_listener=exit_ip + ':53')), flush=True)
    print('PASS exit DNS runtime: public A query/source verified; one unique .fips query answered by loopback; exit count unchanged', flush=True)
    # Stop only the exit fixture; do not alter routes, firewall or resolver config.
    fixture.terminate()
    fixture.wait(timeout=3)
    down_name = 'exit-down-' + os.urandom(16).hex() + '.example.com'
    response = json.loads(ns('dns-guest', 'python3', '-c', PROBE, down_name, '15').stdout)
    print(json.dumps(dict(case='exit-down', observation_window_seconds=15, **response)), flush=True)
    assert response['outcome'] in ('SERVFAIL', 'timeout'), response
    assert response.get('answers', 0) == 0, response
    assert wan.poll() is None and int(wan_count.read_text()) == wan_control_count
    print(json.dumps(dict(case='exit-down IPv4 UDP WAN fallback', wan_before=wan_control_count, wan_after=int(wan_count.read_text()))), flush=True)
    print('PASS bounded IPv4 UDP WAN-decoy fallback test: no successful exit-down answer; decoy count unchanged', flush=True)


def inside(config, host_net, host_mount, dnsmasq, exit_runtime=False):
    assert os.geteuid() == 0
    assert os.readlink('/proc/self/ns/net') != host_net
    assert os.readlink('/proc/self/ns/mnt') != host_mount
    links = json.loads(subprocess.check_output(['ip', '-j', 'link']))
    assert all(x['ifname'] == 'lo' or (x['ifname'] == 'ip6tnl0' and 'UP' not in x['flags']) for x in links)
    print(json.dumps(dict(host_net=host_net, private_net=os.readlink('/proc/self/ns/net'), host_mount=host_mount, private_mount=os.readlink('/proc/self/ns/mnt'))), flush=True)
    subprocess.run(['mount', '--make-rprivate', '/'], check=True)
    subprocess.run(['mount', '-t', 'tmpfs', 'tmpfs', '/run/netns'], check=True)
    r = Runner()
    names = ('bootstrap', 'dns-guest', 'dns-wan')
    def ns(n, *args):
        return r.ns(n, list(args))
    def interrupted(signum, frame):
        raise RuntimeError(f'interrupted {signum}')
    signal.signal(signal.SIGTERM, interrupted)
    resolver_mounted = False
    try:
        if exit_runtime:
            resolver = r.tmp / 'resolv.conf'
            resolver.write_text('nameserver 10.73.3.2\n')
            subprocess.run(['mount', '--bind', str(resolver), '/etc/resolv.conf'], check=True)
            resolver_mounted = True
            assert Path('/etc/resolv.conf').read_text() == resolver.read_text()
            print(json.dumps(dict(resolver_fixture=resolver.read_text(), resolver_mount='private bind; host symlink target not written')), flush=True)
        path = r.tmp / 'dnsmasq.conf'
        path.write_text(config)
        result = r.run([dnsmasq, '--test', '--conf-file=' + str(path)], check=False)
        print(json.dumps(dict(parser_rc=result.returncode, stdout=result.stdout, stderr=result.stderr)), flush=True)
        assert result.returncode == 0, 'generated config parser failure; runtime not attempted'
        for n in names:
            r.run(['ip', 'netns', 'add', n])
            ns(n, 'ip', 'link', 'set', 'lo', 'up')
        for n, i in (('dns-guest', 1), ('dns-wan', 3)):
            iface = 'v' + str(i)
            ns('bootstrap', 'ip', 'link', 'add', iface, 'type', 'veth', 'peer', 'name', 'remote')
            ns('bootstrap', 'ip', 'link', 'set', 'remote', 'netns', n)
            ns('bootstrap', 'ip', 'addr', 'add', f'10.73.{i}.1/24', 'dev', iface)
            ns('bootstrap', 'ip', 'link', 'set', iface, 'up')
            ns(n, 'ip', 'addr', 'add', f'10.73.{i}.2/24', 'dev', 'remote')
            ns(n, 'ip', 'link', 'set', 'remote', 'up')
        if exit_runtime:
            exit_probe(r, ns, config, path, dnsmasq)
            return
        ns('bootstrap', 'ip', 'route', 'add', 'default', 'via', '10.73.3.2')
        rule = 'table inet observe { chain incoming { type filter hook input priority 0; policy accept; udp dport 53 counter; tcp dport 53 counter; }; }'
        subprocess.run(['ip', 'netns', 'exec', 'dns-wan', 'nft', '-f', '-'], input=rule, text=True, check=True)
        def counters():
            data = json.loads(ns('dns-wan', 'nft', '-j', 'list', 'table', 'inet', 'observe').stdout)
            return [e['counter']['packets'] for x in data['nftables'] for e in x.get('rule', {}).get('expr', []) if 'counter' in e]
        # Positive control proves the WAN observation path counts DNS packets.
        ns('bootstrap', 'python3', '-c', "import socket; socket.socket(socket.AF_INET,socket.SOCK_DGRAM).sendto(b'control',('10.73.3.2',53))")
        before = counters()
        assert before == [1, 0], before
        proc = r.popen_ns('bootstrap', [dnsmasq, '--keep-in-foreground', '--conf-file=' + str(path), '--user=nobody', '--group=nogroup', '--pid-file='])
        for attempt in range(30):
            if proc.poll() is not None:
                raise RuntimeError(proc.communicate())
            listeners = ns('bootstrap', 'ss', '-lun').stdout
            if '10.73.1.1:5353' in listeners:
                break
            time.sleep(0.1)
        else:
            raise RuntimeError('dnsmasq not listening within 3 seconds')
        for name in ('portal.example', 'unrelated.example', 'random-9320319f.portal.example'):
            response = json.loads(ns('dns-guest', 'python3', '-c', PROBE, name).stdout)
            print(json.dumps(response), flush=True)
            if name == 'portal.example':
                assert response['rcode'] == 0 and response['answers'] == 1 and response['last_ipv4'] == '10.73.1.1'
            else:
                assert response['rcode'] in (3, 5) and response['answers'] == 0, response
        after = counters()
        print(json.dumps(dict(wan_dns_before=before, wan_dns_after=after)), flush=True)
        assert after == before, 'WAN DNS leakage observed'
        print('PASS bootstrap only: real DNS replies; no paid DNS, FIPS transport or deployment claim', flush=True)
    finally:
        for proc in reversed(r.procs):
            if proc.poll() is None:
                proc.terminate()
            try:
                out, err = proc.communicate(timeout=3)
            except subprocess.TimeoutExpired:
                proc.kill()
                out, err = proc.communicate(timeout=3)
            print(json.dumps(dict(dnsmasq_exit=proc.returncode, stdout=out, stderr=err)), flush=True)
        for n in reversed(names):
            r.run(['ip', 'netns', 'delete', n], check=False)
        if resolver_mounted:
            subprocess.run(['umount', '/etc/resolv.conf'], check=True)
        shutil.rmtree(r.tmp)
        assert not r.run(['ip', 'netns', 'list']).stdout.strip()
        assert not r.tmp.exists()
        print('CLEANUP: child reaped; private registry empty; temporary files removed', flush=True)


def main():
    if not __debug__:
        raise RuntimeError('optimized Python refused')
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--module-repo', required=True)
    p.add_argument('--go', required=True)
    mode = p.add_mutually_exclusive_group()
    mode.add_argument('--inside', nargs=2)
    mode.add_argument('--parse-only', action='store_true', help='test pinned RenderExitDNS output; no sudo, service or network setup')
    p.add_argument('--exit-runtime', action='store_true', help='public and unique .fips A queries through unchanged exit config to labelled UDP fixtures')
    args = p.parse_args()
    if args.exit_runtime and args.parse_only:
        p.error('--exit-runtime and --parse-only are mutually exclusive')
    dnsmasq = shutil.which('dnsmasq')
    if not dnsmasq:
        raise RuntimeError('BLOCKED: dnsmasq missing; no install attempted')
    if args.inside:
        inside(sys.stdin.read(), args.inside[0], args.inside[1], dnsmasq, args.exit_runtime)
        return
    config = render(args.module_repo, args.go, exit_dns=args.parse_only or args.exit_runtime)
    print(json.dumps(dict(module_sha=EXIT_PIN if args.parse_only or args.exit_runtime else PIN, config_sha256=hashlib.sha256(config.encode()).hexdigest(), config=config)), flush=True)
    if args.parse_only:
        print(subprocess.check_output([dnsmasq, '--version'], text=True), flush=True)
        parse_only(config, dnsmasq)
        return
    def resolver_state():
        return dict(sha256=hashlib.sha256(Path('/etc/resolv.conf').read_bytes()).hexdigest(),
                    symlink=os.readlink('/etc/resolv.conf') if Path('/etc/resolv.conf').is_symlink() else None,
                    target=str(Path('/etc/resolv.conf').resolve()))
    before = resolver_state()
    print(json.dumps(dict(host_resolver_before=before)), flush=True)
    try:
        run_isolated(config, args)
    finally:
        after = resolver_state()
        print(json.dumps(dict(host_resolver_after=after)), flush=True)
        assert after == before, 'host resolver changed'


def run_isolated(config, args):
    subprocess.run(['sudo', '-n', 'unshare', '--mount', '--net', '--propagation', 'private',
                    'env', 'TMPDIR=' + tempfile.gettempdir(), 'PATH=' + os.environ['PATH'],
                    'python3', str(Path(__file__).resolve()), '--module-repo', args.module_repo,
                    '--go', args.go, '--inside', os.readlink('/proc/self/ns/net'), os.readlink('/proc/self/ns/mnt')] + (['--exit-runtime'] if args.exit_runtime else []),
                   input=config, text=True, check=True, timeout=60)


if __name__ == '__main__':
    main()
