def parse_only(config, dnsmasq):
    """Parse unchanged generated bytes and a separate invalid control; never serve."""
    results = []
    with tempfile.TemporaryDirectory(prefix='prta-exit-dns-parse-') as temp:
        for label, data in (('generated', config.encode()),
                            ('invalid-control', config.encode() + b'prta-invalid-directive-control\n')):
            path = Path(temp) / (label + '.conf')
            path.write_bytes(data)
            argv = [dnsmasq, '--test', '--conf-file=' + str(path)]
            result = subprocess.run(argv, capture_output=True, text=True, timeout=10)
            print(json.dumps(dict(case=label, argv=argv,
                                  config_sha256=hashlib.sha256(data).hexdigest(),
                                  parser_rc=result.returncode, stdout=result.stdout,
                                  stderr=result.stderr)), flush=True)
            results.append(result.returncode)
    if results[0] != 0:
        raise RuntimeError('module defect: unchanged RenderExitDNS output rejected; see parser diagnostic above')
    if results[1] != 1:
        raise RuntimeError('invalid directive control did not return dnsmasq configuration error (1)')
    print('PASS parse-only: generated exit config accepted; invalid directive rejected; no service started', flush=True)


