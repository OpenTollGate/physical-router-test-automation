/**
 * Tester-uplink drop — E2E acceptance for card t_27e348b5.
 *
 * THE DEFECT THIS PINS
 *   The operator's machine reaches the router over WIFI. Mid-deploy the wizard
 *   reconfigures the router's wireless (STA at step 5, branding at step 7, the
 *   service restart at step 10). That can drop the TESTER's own association, the
 *   SSH session dies with it, and the wizard used to report:
 *
 *       "Setup failed — lost the router — SSH transport died"
 *
 *   with advice about the router's OTHER ethernet port. The install had
 *   succeeded. Live reproduction: this bench laptop's wifi roamed from
 *   192.168.1.0/24 to 10.2.124.0/16 mid-session.
 *
 * WHAT IS REAL HERE
 *   The wizard binary is built from the installer tree and served by the real
 *   binary on a real port; the page is the shipped index.html; the polling path
 *   is the real /api/status/ handler. What is stubbed is only the deploy itself
 *   (/api/deploy, /api/status/<id>) — the two endpoints that need a physical
 *   router — with payloads GENERATED BY THE GO CODE under test (see the
 *   TG_TESTER_DROP_FIXTURE emitter in internal/app/tester_drop_fixture_test.go),
 *   not typed into this file. A regression in the wizard's verdict or wording
 *   changes the fixture and fails this spec.
 *
 * WHY THE CONTROL CASE EXISTS
 *   "The page never says failed" is trivially satisfiable by a wizard that
 *   reports nothing. Case 2 replays a ROUTER-side loss and asserts the wizard
 *   DOES still report a failure with the router-side advice. Without it, this
 *   spec could go vacuously green.
 *
 * RUN
 *   TG_INSTALLER_REPO=/path/to/tollgate-installer \
 *   npx playwright test --config=tests/browser/tester-uplink-drop.config.mjs
 */
import { test, expect } from '@playwright/test';
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const REPO = process.env.TG_INSTALLER_REPO || path.resolve(os.homedir(), 'repos/tollgate-installer');
const PORT = process.env.WIZARD_PORT || '8099';
const BASE = `http://127.0.0.1:${PORT}`;
const GO = process.env.GO_BIN || '/usr/local/go/bin';
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'tester-drop-'));
const BIN = path.join(TMP, 'tollgate-installer');
const FIXTURES = path.join(TMP, 'fixtures');

const FIXTURE_ROUTER = { ip: '192.168.1.1', vendor: 'TollGate', model: 'BenchRouter', firmware: 'OpenWrt 24.10' };
const FIXTURE_LNURL = 'operator@wallet.example';
const FIXTURE_JOB = 'tester-drop-job';

let wizard = null;

function goEnv() {
  return { ...process.env, PATH: `${GO}:${process.env.PATH}`, GOFLAGS: '-mod=mod' };
}

test.beforeAll(async () => {
  // 1. Build the wizard from the installer tree under test. No download: the
  //    binary must be the code this card changed.
  execFileSync('go', ['build', '-o', BIN, '.'], { cwd: REPO, env: goEnv(), stdio: 'inherit', timeout: 300_000 });
  if (!fs.existsSync(BIN)) throw new Error(`wizard binary was not produced at ${BIN}`);

  // 2. Ask the Go code to emit the status payloads for both cases. This is the
  //    anti-vacuity step: the expected wording comes from the implementation.
  //    TG_STATUS_FIXTURE_DIR overrides it with fixtures generated elsewhere —
  //    that is how the PRE-FIX baseline is measured (see the card's evidence),
  //    and it is never used for the registered run.
  fs.mkdirSync(FIXTURES, { recursive: true });
  if (!process.env.TG_STATUS_FIXTURE_DIR) {
    execFileSync('go', ['test', './internal/app', '-run', 'TestEmitTesterDropFixtures', '-count=1'], {
      cwd: REPO, env: { ...goEnv(), TG_TESTER_DROP_FIXTURE: FIXTURES }, stdio: 'inherit', timeout: 300_000,
    });
  } else {
    for (const name of ['tester-side', 'router-side-fail']) {
      fs.copyFileSync(path.join(process.env.TG_STATUS_FIXTURE_DIR, `${name}.json`), path.join(FIXTURES, `${name}.json`));
    }
  }
  for (const name of ['tester-side', 'router-side-fail']) {
    const f = path.join(FIXTURES, `${name}.json`);
    if (!fs.existsSync(f)) throw new Error(`fixture ${f} was not emitted`);
  }

  // 3. Port must be free: a stale wizard would answer instead of ours.
  let holder = '';
  try { holder = execFileSync('ss', ['-ltnp'], { encoding: 'utf8' }).split('\n').filter((l) => l.includes(`:${PORT} `)).join('\n'); } catch {}
  if (holder) throw new Error(`port ${PORT} already in use by a stale process: ${holder}`);

  // 4. Start it, and prove the listener is OUR pid.
  wizard = spawn(BIN, [], { env: { ...process.env, PORT }, stdio: ['ignore', 'pipe', 'pipe'] });
  let out = '';
  wizard.stdout.on('data', (d) => { out += d.toString(); });
  wizard.stderr.on('data', (d) => { out += d.toString(); });

  const deadline = Date.now() + 30_000;
  for (;;) {
    try {
      const r = await fetch(BASE + '/api/config');
      if (r.ok) break;
    } catch {}
    if (Date.now() > deadline) throw new Error(`wizard did not come up on ${BASE}\n${out}`);
    await new Promise((r) => setTimeout(r, 250));
  }
  let listen = '';
  try { listen = execFileSync('ss', ['-ltnp'], { encoding: 'utf8' }).split('\n').filter((l) => l.includes(`:${PORT} `)).join('\n'); } catch {}
  if (!listen.includes(`pid=${wizard.pid}`)) {
    throw new Error(`port ${PORT} is not held by the wizard we spawned (pid=${wizard.pid}): ${listen}`);
  }
});

test.afterAll(async () => {
  if (wizard && wizard.pid) {
    try { process.kill(wizard.pid, 'SIGTERM'); } catch {}
    await new Promise((r) => setTimeout(r, 1000));
    try { process.kill(wizard.pid, 'SIGKILL'); } catch {}
  }
  fs.rmSync(TMP, { recursive: true, force: true });
});

/**
 * Install the backend doubles via the BROWSER, so the page's own code (fetch and
 * pollStatus) runs unchanged: the wizard behaves exactly as it does against a
 * router, it just talks to a canned job.
 * @param {import('@playwright/test').Page} page
 * @param {string} fixtureName
 */
async function stubBackend(page, fixtureName) {
  const status = JSON.parse(fs.readFileSync(path.join(FIXTURES, `${fixtureName}.json`), 'utf8'));

  await page.route('**/api/scan', (r) =>
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ routers: [FIXTURE_ROUTER] }) }));
  // No host-key refusal: the trust prompt is a different surface (see
  // deploy-trust-ui.mjs) and must not gate this case.
  await page.route('**/api/identify', (r) =>
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(FIXTURE_ROUTER) }));
  await page.route('**/api/prestage', (r) =>
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ job_id: FIXTURE_JOB }) }));
  await page.route('**/api/deploy', (r) =>
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ job_id: FIXTURE_JOB }) }));
  await page.route(`**/api/status/${FIXTURE_JOB}`, (r) =>
    r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(status) }));

  return status;
}

/**
 * Walk the wizard to a deploy and let it reach a terminal state.
 * @param {import('@playwright/test').Page} page
 */
async function driveToTerminal(page) {
  await page.goto(BASE, { waitUntil: 'domcontentloaded' });

  // The wizard autoscans; select the discovered router.
  await page.locator('#router-select').waitFor({ state: 'visible', timeout: 30_000 });
  await expect
    .poll(async () => (await page.locator('#router-select option').allTextContents()).join('|'), { timeout: 30_000 })
    .toContain(FIXTURE_ROUTER.ip);
  await page.locator('#router-select').selectOption({ index: 0 }).catch(async () => {
    const opts = await page.locator('#router-select option').all();
    for (const o of opts) {
      const t = await o.textContent();
      if (t && t.includes(FIXTURE_ROUTER.ip)) { await page.locator('#router-select').selectOption(await o.getAttribute('value')); break; }
    }
  });

  await page.locator('#password').fill('bench-password');
  await page.locator('#lnurl').fill(FIXTURE_LNURL);
  await expect(page.locator('#deploy-btn')).toBeEnabled({ timeout: 15_000 });
  await page.locator('#deploy-btn').click();

  // A terminal state is reached by UI state, not by a sleep.
  await expect(
    page.locator('#pending-view:not(.hidden), #error-view:not(.hidden)'),
    'the wizard must reach a terminal view',
  ).toBeVisible({ timeout: 60_000 });
}

test.describe('tester-uplink drop is not reported as an install failure', () => {
  test('wifi association lost mid-run: actionable, and never "failed"', async ({ page }) => {
    const status = await stubBackend(page, 'tester-side');
    // Guard: the fixture must actually be the non-fatal shape, otherwise this
    // case would be asserting the wrong story.
    expect(status.status, 'the tester-side fixture must be a NON-fatal job').toBe('pending');

    await driveToTerminal(page);

    // The error view must NOT be shown. This is the card's requirement (iv).
    await expect(page.locator('#error-view'), 'a tester-side loss must not show the failure view').toBeHidden();

    const heading = await page.locator('#pending-title').innerText();
    const detail = await page.locator('#pending-detail').innerText();
    const shown = `${heading}\n${detail}`;

    // It must say the install is not being called a failure...
    expect(heading).toMatch(/not an install failure/i);
    expect(shown.toLowerCase()).not.toContain('installation failed');
    expect(shown.toLowerCase()).not.toContain('setup failed');

    // ...be actionable: which SSID to join and what to do next...
    expect(detail).toContain('!TollGate-AB12');
    expect(detail).toContain('c08r4d0r-AB12');
    expect(detail).toContain('Re-check');

    // ...and name the tester's own connection as the thing that changed, which
    // is the whole distinction the card asks for.
    expect(detail).toMatch(/wlp59s0/);
    expect(detail).toContain('192.168.1.20/24');
    expect(detail).toContain('10.2.124.120/16');
    expect(detail).toMatch(/THIS machine lost its network connection/i);

    // Re-check must be offered (the action that does not re-deploy).
    await expect(page.locator('#recheck-btn')).toBeVisible();
  });

  test('control: a ROUTER-side loss still reports a failure with router advice', async ({ page }) => {
    const status = await stubBackend(page, 'router-side-fail');
    expect(status.status, 'the control fixture must be a failed job').toBe('failed');

    await driveToTerminal(page);

    // The failure view IS shown — the fix must not silence real faults.
    await expect(page.locator('#error-view')).toBeVisible({ timeout: 30_000 });
    await expect(page.locator('#pending-view')).toBeHidden();

    const detail = await page.locator('#error-detail').innerText();
    // Today's router-side advice must survive verbatim...
    expect(detail).toContain('OTHER ethernet port');
    // ...and a wifi tester is additionally told about their own association.
    expect(detail).toContain('YOUR association');
  });
});
